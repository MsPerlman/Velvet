/**
 * velvetdesk opens
 *
 * the engine had been running on the desktop since the early spikes: login, session encrypted by
 * dpapi, sync, reading an encrypted room, all of it verified for months by `:verif-bureau`.
 * what was missing was not the machinery, it was a window. this file is that
 *
 * three states and not one more. starting, logging in, or inside. a loading screen that told
 * "restoring a session" from "first sync" would name steps nobody waits for separately
 */
fun main() {
    // what the installation adds to the shared model, before anything displays it
    li.velvetchat.core.model.LienInvitation.base = Prive.BASE_INVITATION
    Natif.preparer()
    // a logout asked for on the previous run: the folder is held by nobody here
    Donnees.purgerSiDemande()
    // and the stores of an account whose session has gone: without this, the next login runs into a
    // store that does not belong to it
    Donnees.ecarterMagasinOrphelin()
    application {
    // 1280 by 800: enough for the three columns without taking the whole screen
    val etatFenetre = rememberWindowState(width = 1280.dp, height = 800.dp)
    Window(
        // an update downloaded and verified installs itself on close (`MiseAJour.kt`)
        onCloseRequest = { MiseAJourBureau.installer(relancer = false); exitApplication() },
        title = "VelvetDesk",
        // the taskbar and alt tab: without it windows shows java's coffee cup. generated by
        // `tools/icones-velvet.py`, like every icon
        icon = remember { androidx.compose.ui.graphics.painter.BitmapPainter(
            androidx.compose.ui.res.useResource("velvet-icone.png") { androidx.compose.ui.res.loadImageBitmap(it) }
        ) },
        // no system frame: the top bar is the room's header, in the theme, like on the reference.
        // what the frame used to do, move, maximise, resize, close, is rebuilt in `Fenetre.kt`
        undecorated = true,
        state = etatFenetre,
    ) {
        // the same minimum the resize handles enforce, told to the system as well. they only
        // clamp the drags this app draws itself, and windows resizes a window by other routes
        LaunchedEffect(window) { window.minimumSize = java.awt.Dimension(LARGEUR_MIN, HAUTEUR_MIN) }
        val fenetre = remember(window) { Fenetre(window, etatFenetre) }
        PosageFenetre(fenetre)
        // true fullscreen follows the call, and nothing else touches `placement` here: we
        // remember what was there before so we can go back, otherwise leaving fullscreen
        // would hand a floating window to somebody who had maximised it
        var placementAvant by remember {
            mutableStateOf(androidx.compose.ui.window.WindowPlacement.Floating)
        }
        androidx.compose.runtime.LaunchedEffect(AppelBureau.ecranEntier) {
            if (AppelBureau.ecranEntier) {
                placementAvant = etatFenetre.placement
                etatFenetre.placement = androidx.compose.ui.window.WindowPlacement.Fullscreen
            } else if (etatFenetre.placement == androidx.compose.ui.window.WindowPlacement.Fullscreen) {
                etatFenetre.placement = placementAvant
            }
        }
        androidx.compose.runtime.LaunchedEffect(window) {
            arrondirCoins(window)
            Ancrage.activer(window)
            // the bundled themes are dropped into the data folder on first launch: without that,
            // the file picker would open on an empty folder and the choice would have nothing to
            // offer. it never overwrites a file already there
            ThemeVelvet.preparerLivres()
        }
        // the language: the chosen one, failing that windows'. changing it recomposes everything
        var langue by remember {
            mutableStateOf(
                Langue.depuisCode(Reglages.lire("langue") ?: java.util.Locale.getDefault().language),
            )
        }
        // what does not compose, date formats, system sentences, reads `horsUi`, hence this
        langueCourante = langue
        androidx.compose.runtime.CompositionLocalProvider(
            LocalFenetre provides fenetre,
            LocalLangue provides langue,
            LocalChoisirLangue provides { choisie: Langue ->
                langue = choisie
                langueCourante = choisie
                Reglages.ecrire("langue", choisie.code)
            },
        ) {
            VelvetTheme(
                // the user's theme, when they put one down, in `%APPDATA%\VelvetDesk\theme.json`
                //
                // the `design` module has carried a full loader for months, with a safe fallback on
                // the default, unknown keys ignored and the pattern preserved, its readme promised
                // changing a colour with no recompilation, and nobody called it: both apps built a
                // `Theme()` in code. so the promise was false, and the themes shipped in
                // `design/themes/` served no purpose
                //
                // a missing or unreadable file gives the default theme, which is the loader's
                // guarantee, and what makes it safe to edit that file while the app runs
                //
                // read through `ThemeVelvet`, so observable: switching theme from the menu applies
                // at once with no restart. it is a `mutableIntStateOf` this read consults, exactly
                // like the wallpaper
                theme = ThemeVelvet.courant.let {
                    // emoji on their own drawn large: 48 on the desktop reference, three times the
                    // 16 point body, where the phone keeps its 40. the desktop was drawing 40
                    it.copy(typography = it.typography.copy(jumboEmojiScale = 3f))
                },
                famille = policeVelvet(),
                policeEmoji = policeEmoji(),
            ) {
                androidx.compose.runtime.CompositionLocalProvider(LocalReglagesEmojis provides ReglagesEmojisBureau) {
                    Box(Modifier.fillMaxSize()) {
                        Racine()
                        BordsRedimension()
                    }
                }
            }
        }
    }
    }
}

private sealed interface Etat {
    data object Demarrage : Etat
    data object Connexion : Etat
    data class Pret(val moteur: MatrixEngine) : Etat
    data class Casse(val quoi: String) : Etat
}

@Composable
private fun Racine() {
    val t = textes()
    val tokens = LocalTokens.current

    // one engine for the window's lifetime. `remember` with no key: rebuilding it on a
    // recomposition would reopen the sdk's database underneath itself
    val moteur = remember {
        RustMatrixEngine(
            dataPath = Donnees.session.absolutePath,
            cachePath = Donnees.cache.absolutePath,
            logToStdout = System.getProperty("velvet.verbeux") != null,
            // the global cosmetics catalogue, plates, decorations, effects. hardcoded like the
            // server: without it the desktop's picker was limited to the servers' catalogues, empty
            // for plates, so a grid reduced to "none"
            aliasCatalogue = Prive.CATALOGUE_COSMETIQUES,
            // only one account joins that room: opening it made everybody join a catalogue nobody
            // asked for. see `prive.properties`
            intendantCatalogue = Prive.INTENDANT,
            // the voice token service. empty and voice reports itself unconfigured, which
            // is a supported state: the homeserver does not advertise this address
            urlJetonVocal = Prive.JETON_VOCAL,
        )
    }
    val sessions = remember { WindowsSessionStore(Donnees.session) }
    // an oauth session's tokens change every few minutes, and the refresh token is single use
    remember { moteur.surSessionRenouvelee { sessions.save(it) } }
    var etat by remember { mutableStateOf<Etat>(Etat.Demarrage) }
    val porteeConnexion = androidx.compose.runtime.rememberCoroutineScope()

    // device verification, which only existed on the phone
    //
    // without it a fresh desktop session stays unattested: the encrypted history is unreadable and,
    // on an account that requires verification, you simply do not get in. the screen is the phone's
    // (`ui-commun`) with its two paths, emoji comparison from an already connected device, or a
    // recovery key
    var acces by remember { mutableStateOf<li.velvetchat.core.AccessState>(
        li.velvetchat.core.AccessState.SignedOut,
    ) }
    var verifieIci by remember { mutableStateOf(false) }
    // "later" holds for this session only: the question comes back at the next launch, because it
    // has not gone away. same rule as on the phone
    var reporte by remember { mutableStateOf(false) }
    LaunchedEffect(etat) {
        if (etat !is Etat.Pret) return@LaunchedEffect
        essayer { moteur.accessFlow().collect { acces = it } }
            .onFailure { grogner("etat de verification illisible", it) }
    }

    LaunchedEffect(Unit) {
        etat = runCatching {
            moteur.initPlatform()
            val stockee = sessions.load()
            if (stockee == null) {
                Etat.Connexion
            } else {
                moteur.restore(stockee)
                moteur.startSync()
                rejoindreLeCanalDeMiseAJour(moteur)
                Etat.Pret(moteur)
            }
        }.getOrElse { Etat.Casse(it.message ?: it::class.simpleName.orEmpty()) }
    }

    Box(Modifier.fillMaxSize().background(tokens.bg)) {
        when (val e = etat) {
            is Etat.Demarrage -> Message(t.velvetDemarre)

            is Etat.Connexion -> EcranConnexion(
                // the installation's server, read from `prive.properties`: velvet is not a generic
                // matrix client, it is one server's client, and which server is none of the source
                // code's business. left empty, the field opens empty, and it stays editable either
                // way, for a development homeserver on the local network
                serveurParDefaut = Prive.SERVEUR_PAR_DEFAUT,
                onConnexion = { serveur, identifiant, motDePasse ->
                    // a second pass, because you can arrive here after a session that turned out
                    // unreadable mid way rather than at startup
                    Donnees.ecarterMagasinOrphelin()
                    // errors go back up to `EcranConnexion`, which shows them under the form.
                    // swallowing them here would leave a button that does nothing
                    val session = moteur.login(serveur, identifiant, motDePasse)
                    sessions.save(session)
                    moteur.startSync()
                    rejoindreLeCanalDeMiseAJour(moteur)
                    etat = Etat.Pret(moteur)
                },
                parNavigateur = { moteur.connexionParNavigateur(it) },
                onConnexionNavigateur = { serveur ->
                    Donnees.ecarterMagasinOrphelin()
                    val session = NavigateurBureau.allerRetour { retour, ouvrir ->
                        moteur.loginNavigateur(serveur, retour, creation = false, ouvrir = ouvrir)
                    }
                    sessions.save(session)
                    moteur.startSync()
                    rejoindreLeCanalDeMiseAJour(moteur)
                    etat = Etat.Pret(moteur)
                },
                onInscriptionNavigateur = { serveur, code ->
                    val invitation = li.velvetchat.core.model.CodeInvitation.decoder(code)
                        ?: throw IllegalArgumentException(tr("Code d'invitation illisible.", "Unreadable invite code."))
                    Donnees.ecarterMagasinOrphelin()
                    val session = NavigateurBureau.allerRetour { retour, ouvrir ->
                        moteur.loginNavigateur(serveur, retour, creation = true, ouvrir = ouvrir)
                    }
                    sessions.save(session)
                    moteur.startSync()
                    runCatching { moteur.joinServer(invitation.idEspace) }
                    rejoindreLeCanalDeMiseAJour(moteur)
                    etat = Etat.Pret(moteur)
                },
            )

            is Etat.Pret -> {
                val besoin = acces as? li.velvetchat.core.AccessState.VerificationRequired
                if (besoin != null && !verifieIci && !reporte) {
                    VerificationScreen(
                        engine = e.moteur,
                        canUseRecoveryKey = besoin.canUseRecoveryKey,
                        aUnAppareilTemoin = besoin.aUnAppareilTemoin,
                        onVerifie = { verifieIci = true },
                        onPlusTard = { reporte = true },
                    )
                } else {
                    Bureau(e.moteur) {
                // logging out means starting over. the token is revoked, the session erased, and
                // the sdk's store marked for purging, which stays open as long as this process
                // lives, hence the relaunch
                porteeConnexion.launch {
                    runCatching { e.moteur.deconnecter() }
                    sessions.clear()
                    Donnees.demanderPurge()
                    relancerEtQuitter()
                }
                    }
                }
            }

            // no crafted error screen: at this stage, what breaks here breaks at startup, and the
            // raw message is more useful than a pretty page
            is Etat.Casse -> Message(t.demarrageImpossible(e.quoi))
        }
        // outside the desktop shell no header carries the window buttons, so without this bar the
        // undecorated window would neither move nor close
        if (etat !is Etat.Pret) BarreFenetreSeule(Modifier.align(Alignment.TopCenter))
        (etat as? Etat.Pret)?.let {
            BandeauMiseAJour(it.moteur, Modifier.align(Alignment.BottomCenter))
        }
    }
}

/**
 * relaunches velvetdesk and closes this one. with no executable, launched from gradle, it only
 * closes
 *
 * the relaunch waits two seconds through a small script, like the update installer: started
 * straight away, the new instance would find the sdk's store still held by this one and could
 * neither purge nor open it
 */
private fun relancerEtQuitter() {
    val exe = System.getProperty("jpackage.app-path")
    // the linux archive's launcher passes itself, there is no jpackage there
    val lanceur = System.getProperty("velvet.lanceur")
    if (exe == null && lanceur != null) {
        runCatching { ProcessBuilder("sh", "-c", "sleep 2; exec \"\$0\"", lanceur).start() }
    } else if (exe != null) {
        val script = File(Donnees.racine, "relancer.cmd")
        runCatching {
            script.writeText(
                buildString {
                    appendLine("@echo off")
                    appendLine("timeout /t 2 /nobreak >nul")
                    appendLine("start \"\" \"$exe\"")
                    appendLine("exit")
                },
            )
            ProcessBuilder("cmd", "/c", "start", "\"\"", "/min", script.absolutePath).start()
        }
    }
    kotlin.system.exitProcess(0)
}

@Composable
private fun Message(texte: String) {
    val tokens = LocalTokens.current
    Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
        Text(texte, color = tokens.textSecondary)
    }
}

/**
 * joining the space where versions are announced
 *
 * a version announcement is a space's state event: you only see it if you are in that space. nobody
 * joined it, so the automatic update could never have worked for anybody. the client was looking
 * everywhere and the announcement was nowhere it could see
 *
 * we join, we do not get invited: an account cannot invite itself, and putting a privileged account
 * in the client to send the invitation would amount to shipping a token. the space is public, so we
 * join it. same result, nothing to accept, no secret embedded
 *
 * on every launch and not only on login: joining twice costs nothing, and already open sessions
 * would otherwise never get the chance to go in. the failure is swallowed, since a client with no
 * update channel is a client that works
 */
private suspend fun rejoindreLeCanalDeMiseAJour(moteur: MatrixEngine) {
    // announcements now live in the installation's hidden room, which the engine joins by
    // itself. a separate channel is only joined when the server still names one
    val canal = li.velvetchat.core.Installation.config.value.misesAJour.takeIf { it.isNotBlank() } ?: return
    runCatching { moteur.joinServer(canal) }
}
